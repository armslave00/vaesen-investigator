test('ten base archetypes match the independent book pages, including priest cap 6 and servant Strength', () => {
  assert.equal(rules.archetypes.length, 11);
  assert.equal(rules.archetypes.filter((row) => row.verified).length, 10);
  for (const [name, minimum, maximum, attribute, skill, page] of expectedArchetypes) {
    const actual = named(rules.archetypes, name);
    assert.deepEqual([actual.resourceMin, actual.resourceMax, actual.mainAttribute, actual.mainSkill, actual.source.pdfPage], [minimum, maximum, attribute, skill, page], name);
    assert.equal(actual.talents.length, 3);
    assert.equal(actual.verified, true);
    for (const talent of actual.talents) assert.equal(named(rules.talents, talent).category, name);
    assert.equal(actual.equipmentChoices.length, 3);
  }
  const hunter = named(rules.archetypes, '吸血鬼猎人');
  assert.deepEqual([hunter.resourceMin, hunter.resourceMax, hunter.mainAttribute, hunter.mainSkill], [1, 3, '精准', '近身战斗']);
  assert.equal(hunter.verified, false);
  assert.equal(hunter.source.pdfPage, null);
});

