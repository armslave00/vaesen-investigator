test('food and disguise semantics do not grant bonuses to waived or replaced checks', () => {
  // PDF 79 says food removes the need for Strength checks, and fine disguises
  // allow Manipulation to replace Stealth. The original table bonus is retained.
  for (const name of ['粗制干粮', '营养食品']) {
    const food = named(rules.equipment, name);
    assert.equal(food.bonus, 1);
    assert.deepEqual(food.skills, []);
    assert.match(food.effect, /不需要力量检定/);
    const engine = new RulesEngine(workbook, rules, {
      '角色卡!D20': 3, '角色卡!D23': 1, '角色卡!A30': name,
    });
    assert.equal(engine.roll({ kind: 'skill', skill: '力量', equipmentRows: [30] }).pool, 4);
  }
  const disguise = named(rules.equipment, '高档伪装物');
  assert.equal(disguise.bonus, 2);
  assert.deepEqual(disguise.skills, ['操控人心']);
  assert.match(disguise.effect, /操控人心检定替代隐秘行动/);
  const engine = new RulesEngine(workbook, rules, {
    '角色卡!I20': 4, '角色卡!I23': 3, '角色卡!S20': 2,
    '角色卡!S22': 1, '角色卡!A30': '高档伪装物',
  });
  assert.equal(engine.roll({ kind: 'skill', skill: '隐秘行动', equipmentRows: [30] }).pool, 7);
  assert.equal(engine.roll({ kind: 'skill', skill: '操控人心', equipmentRows: [30] }).pool, 5);
});

