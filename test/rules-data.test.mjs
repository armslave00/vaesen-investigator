test('every book source resolves to an actual Markdown section and PDF page anchor, while expansion sources cite real workbook cells', () => {
  const cache = new Map();
  function verifySource(reference, label) {
    assert.ok(reference && typeof reference === 'object', label);
    if (reference.pdfPage === null) {
      assert.match(reference.label, /基础规则书未核验/, label);
      const sheet = workbook.sheets.find((item) => item.name === reference.sheet);
      assert.ok(sheet, label);
      const firstCell = reference.range.split(':')[0];
      assert.ok(Object.hasOwn(sheet.cells, firstCell), label);
      return;
    }
    assert.equal(reference.document, '北欧奇谭规则书.pdf', label);
    assert.ok(Number.isInteger(reference.pdfPage) && reference.pdfPage >= 1 && reference.pdfPage <= 240, label);
    assert.equal(reference.printedPage, reference.pdfPage - 4, label);
    if (!cache.has(reference.markdown)) cache.set(reference.markdown, readFileSync(new URL('../' + reference.markdown, import.meta.url), 'utf8'));
    const markdown = cache.get(reference.markdown);
    assert.ok(markdown.includes('<a id="pdf-page-' + reference.pdfPage + '"></a>'), label + ' PDF anchor');
    assert.ok(markdown.includes('<a id="' + reference.anchor + '"></a>'), label + ' section anchor');
  }
  for (const collection of ['archetypes', 'talents', 'resources', 'armor', 'weapons', 'equipment', 'cover', 'services', 'ageGroups', 'skills', 'warnings']) {
    for (const item of rules[collection]) {
      verifySource(item.source, collection + ':' + (item.name ?? item.code ?? item.value));
      if (item.adjustmentSource) verifySource(item.adjustmentSource, collection + ':adjustment');
    }
  }
  for (const [name, entry] of Object.entries(rules.rules)) {
    verifySource(entry.source, 'rules:' + name);
    if (entry.skillSource) verifySource(entry.skillSource, 'rules:' + name + ':skills');
  }
  const pdf = readFileSync(new URL('../' + rules.source.path, import.meta.url));
  assert.equal(createHash('sha256').update(pdf).digest('hex'), rules.source.sha256);
});
